#!/usr/bin/env python3
"""Generates Cakewalk .ins instrument definitions for Yamaha XG, General MIDI and
General MIDI Level 2 that are not part of the Roland insdef set.

Inputs (text extracted from the public documents):
  QY100E2.txt   - Yamaha QY100 Data List (XG Normal/SFX voice list, XG drum voice list)
  gm2.wiki      - Wikipedia "General MIDI Level 2" article wikitext
and, for the note lists of the XG drum kits other than the Standard Kit and the SFX kits,
  reference/openmidiproject/MU1000_MU2000.ins (see tools/xg_drum_lists.py)
"""
import re, sys, os
sys.dont_write_bytecode = True  # no __pycache__ in tools/
import xg_drum_lists

def write_ins(path, title, sections):
    with open(path, "w", newline="\r\n") as f:
        f.write("; ----------------------------------------------------------------------\n")
        f.write("; Cakewalk Instrument Definition File\n; %s\n; Generated by tools/gen_ins.py for ImMidi\n" % title)
        f.write("; ----------------------------------------------------------------------\n\n")
        for kind in (".Patch Names", ".Note Names", ".Instrument Definitions"):
            f.write(kind + "\n\n")
            for name, lines in sections.get(kind, []):
                f.write("[%s]\n" % name)
                for l in lines: f.write(l + "\n")
                f.write("\n")

# ---------------------------------------------------------------- XG
def parse_xg_normal(txt):
    pages = re.split(r"=====PAGE (\d+)=====", txt)
    body = ""
    for i in range(1, len(pages), 2):
        if pages[i] in ("2", "3"): body += pages[i + 1] + "\n"
    head, _, sfx = body.partition("128 0 Gunshot 1")
    head += "\n128 0 Gunshot 1\n"
    banks = {}   # lsb -> {prog: name}
    prog = 0
    for line in head.split("\n"):
        line = line.strip()
        m = re.match(r"^(.*?)\s+(\d)$", line)
        if not m: continue
        rest = m.group(1)
        toks = rest.split()
        # drop category tokens before the first pure number
        while toks and not toks[0].isdigit(): toks.pop(0)
        if not toks: continue
        nums = []
        while toks and toks[0].isdigit() and len(nums) < 2: nums.append(int(toks.pop(0)))
        name = " ".join(toks).strip()
        if not name: continue
        if len(nums) == 2 and nums[0] == prog + 1:
            prog, lsb = nums
        elif len(nums) == 2:
            # a name that starts with a number token
            lsb = nums[0]; name = str(nums[1]) + " " + name
        else:
            lsb = nums[0]
        banks.setdefault(lsb, {})[prog] = name
    # SFX voices (MSB 64): "N name elem" per program
    sfxv = {}
    for line in sfx.split("MSB=064")[0].split("\n"):
        m = re.match(r"^\s*(\d+)\s+(\S.*?)\s+(\d)\s*$", line)
        if m: sfxv[int(m.group(1))] = m.group(2)
    return banks, sfxv

def parse_xg_drums(txt):
    pages = re.split(r"=====PAGE (\d+)=====", txt)
    notes = {}
    for i in range(1, len(pages), 2):
        if pages[i] != "4": continue
        for line in pages[i + 1].split("\n"):
            m = re.match(r"^(\d+) [A-G]#? ?-?\d\s+(?:\d\s+)?(?:O\s+)?(.*?)\s+1(?:\s|$)", line)
            if m:
                n = int(m.group(1)); name = m.group(2)
                for a, b in (("Fin ger", "Finger"), ("Se q", "Seq"), ("Ti ght", "Tight"), ("Dr y", "Dry"),
                             ("Li ght", "Light"), ("Snapp y", "Snappy"), ("C ymbal", "Cymbal"), ("Hi gh", "High"),
                             ("Bon go", "Bongo"), ("Con ga", "Conga"), ("A gogo", "Agogo"), ("Lon g", "Long"),
                             ("Trian gle", "Triangle"), ("Jin gle", "Jingle")):
                    name = name.replace(a, b)
                notes[n] = name.strip()
    notes[49] = "Crash Cymbal 1"; notes[51] = "Ride Cymbal 1"
    return notes

