def gen_gm(wiki, out_gm, out_gm2):
    voices, kits = parse_gm2(wiki)
    gm1 = {p: n for (p, b), n in voices.items() if b == 0}
    assert len(gm1) == 128, len(gm1)
    notes = [("General MIDI Drums", ["%d=%s" % kv for kv in sorted(GM_DRUM_NOTES.items())])]
    write_ins(out_gm, "General MIDI Level 1",
        {".Patch Names": [("General MIDI", ["%d=%s" % (p - 1, n) for p, n in sorted(gm1.items())]),
                          ("General MIDI Drum Kits", ["0=Standard Kit"])],
         ".Note Names": notes,
         ".Instrument Definitions": [("General MIDI", ["Patch[*]=General MIDI"]),
                                     ("General MIDI Drums", ["Patch[*]=General MIDI Drum Kits",
                                      "Key[*,*]=General MIDI Drums", "Drum[*,*]=1"])]})
    banks = sorted({b for (p, b) in voices})
    patch = [("GM2 Bank %d" % b, ["%d=%s" % (p - 1, n) for (p, bb), n in sorted(voices.items()) if bb == b]) for b in banks]
    patch.append(("GM2 Drum Kits", ["%d=%s" % (p - 1, n) for p, n in sorted(kits.items())]))
    write_ins(out_gm2, "General MIDI Level 2",
        {".Patch Names": patch, ".Note Names": [("GM2 Drums", ["%d=%s" % kv for kv in sorted(GM_DRUM_NOTES.items())])],
         ".Instrument Definitions": [("General MIDI Level 2", ["Patch[%d]=GM2 Bank %d" % (121 * 128 + b, b) for b in banks] +
                                      ["Patch[*]=GM2 Bank 0"]),
                                     ("General MIDI Level 2 Drums", ["Patch[15360]=GM2 Drum Kits", "Patch[*]=GM2 Drum Kits",
                                      "Key[*,*]=GM2 Drums", "Drum[*,*]=1"])]})
    print("GM2 voices:", len(voices), "banks:", banks)

if __name__ == "__main__":
    src, dst = sys.argv[1], sys.argv[2]
