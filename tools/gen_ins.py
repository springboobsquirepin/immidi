def gen_xg(qy, out):
    txt = open(qy, encoding="utf-8").read()
    banks, sfxv = parse_xg_normal(txt)
    notes = parse_xg_drums(txt)
    patch = []
    for lsb in sorted(banks):
        patch.append(("Yamaha XG Bank %d" % lsb, ["%d=%s" % (p - 1, n) for p, n in sorted(banks[lsb].items())]))
    patch.append(("Yamaha XG SFX Voices", ["%d=%s" % (p - 1, n) for p, n in sorted(sfxv.items())]))
    patch.append(("Yamaha XG Drum Kits", ["%d=%s" % (p - 1, n) for p, n in sorted(XG_KITS.items())]))
    patch.append(("Yamaha XG SFX Kits", ["0=SFX Kit 1", "1=SFX Kit 2"]))
    note = [("Yamaha XG Standard Kit", ["%d=%s" % (n, s) for n, s in sorted(notes.items())]),
            ("Yamaha XG SFX Kit 1", ["%d=%s" % (n, s) for n, s in XG_SFX_KIT_1]),
            ("Yamaha XG SFX Kit 2", ["%d=%s" % (n, s) for n, s in XG_SFX_KIT_2])]
    # The other kits: the Standard Kit with their own sounds (MU1000/MU2000 list book).
    mu = xg_drum_lists.load()
    keys = []
    for key, (kit, _) in sorted(xg_drum_lists.XG_KITS.items(), key=lambda kv: kv[0][1]):
        if key == (127, 0):
            continue
        own = xg_drum_lists.own_notes(mu, key, notes)
        note.append(("Yamaha XG " + kit, ["BasedOn=Yamaha XG Standard Kit"] + ["%d=%s" % kv for kv in sorted(own.items())]))
        keys.append("Key[16256,%d]=Yamaha XG %s" % (key[1], kit))
    inst = [("Yamaha XG", ["Patch[%d]=Yamaha XG Bank %d" % (lsb, lsb) for lsb in sorted(banks)] +
             ["Patch[8192]=Yamaha XG SFX Voices", "Patch[*]=Yamaha XG Bank 0"]),
            ("Yamaha XG Drums", ["Patch[16256]=Yamaha XG Drum Kits", "Patch[16128]=Yamaha XG SFX Kits",
                                 "Patch[*]=Yamaha XG Drum Kits", "Key[16128,0]=Yamaha XG SFX Kit 1",
                                 "Key[16128,1]=Yamaha XG SFX Kit 2"] + keys + ["Key[*,*]=Yamaha XG Standard Kit", "Drum[*,*]=1"])]
    write_ins(out, "Yamaha XG (XG voice set as listed in the Yamaha QY100 data list; drum kits other than\n"
                   "; the Standard and SFX kits from the MU1000/MU2000 list book, after the instrument definition\n"
                   "; by kuzu / openmidiproject)",
              {".Patch Names": patch, ".Note Names": note, ".Instrument Definitions": inst})
    print("XG banks:", len(banks), "voices:", sum(len(v) for v in banks.values()), "sfx:", len(sfxv), "drum notes:", len(notes))

# ---------------------------------------------------------------- GM / GM2
def clean_wiki(s):
    s = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]*)\]\]", r"\1", s)
    s = re.sub(r"<ref.*?(/>|</ref>)", "", s)
    s = re.sub(r"'''?", "", s)
    return s.strip()

def parse_gm2(wiki):
    txt = open(wiki, encoding="utf-8").read()
    mel = txt.split("====Melodic sounds====")[1].split("==== Drum sounds ====")[0]
    rows = mel.split("|-")
    voices = {}   # (prog, bank) -> name
    prog = None
    for r in rows:
        cells = [c.strip() for c in r.strip().split("\n") if c.strip().startswith("|") and not c.strip().startswith("|}")]
        cells = [c[1:].strip() for c in cells]
        cells = [c.split("|")[-1].strip() if not c.startswith("[[") and "|" in c and "=" in c.split("|")[0] else c for c in cells]
        if not cells: continue
        if len(cells) == 3:
            if not cells[1].isdigit(): continue
            m = re.search(r"(\d+)\s*$", cells[0]); prog = int(m.group(1)); bank = int(cells[1]); name = clean_wiki(cells[2])
        elif len(cells) == 2 and prog is not None and cells[0].isdigit():
            bank = int(cells[0]); name = clean_wiki(cells[1])
        else:
            continue
        voices[(prog, bank)] = name
    kits = {1: "Standard Kit", 9: "Room Kit", 17: "Power Kit", 25: "Electronic Kit", 26: "TR-808 Kit",
            33: "Jazz Kit", 41: "Brush Kit", 49: "Orchestra Kit", 57: "Sound FX Kit"}
    return voices, kits

